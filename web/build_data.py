#!/usr/bin/env python3
"""Write web/data.js for the browser: lag3's trained network, its vocabularies, its training windows, and the held-out
machine library. Run after retraining lag3. Weights are rounded to 5 decimals; the check below confirms that changes no
prediction on any training window."""
import json, sys
from pathlib import Path

WEB = Path(__file__).resolve().parent
M = WEB.parent / "machines"
sys.path.insert(0, str(M / "lag3" / "derived"))
import lag3, lag1, lag0  # noqa: E402

D = json.loads((M / "lag3" / "fixtures" / "lag3_training.json").read_text())
ref = lag3.utm_program(lag3.held_out_source("invert", "0"))
emits = {n: e for n, e, _ in lag1.Net(ref).vocab_out}
library = {}
for name, (desc, body) in lag3.HELD_OUT.items():
    src = lag3.held_out_source(name, "0")
    library[name] = {"description": desc, "start": lag0.parse_tm0(src).start,
                     "rules": [l.strip() for l in body.strip().splitlines()]}
examples = {"increment": "01011", "decrement": "10100", "invert": "1011001", "parity": "1101",
            "div3": "1001", "unary-add": "111_11", "palindrome": "10101"}
data = {
    "vin": D["vin"], "vout": D["vout"], "emits": emits, "heads": D["architecture"]["heads"],
    "weights": {k: [[round(x, 5) for x in row] for row in v] for k, v in D["weights"].items()},
    "train": D["train_windows"], "trainPredictions": D["train_predictions"],
    "library": library, "examples": examples,
    "training": {k: D["training_data"][k] for k in ("random_machines", "windows")},
}
(WEB / "data.js").write_text("// Generated by web/build_data.py from machines/lag3. Do not edit.\nwindow.TCT_DATA = "
                             + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote web/data.js ({(WEB / 'data.js').stat().st_size // 1024} KB)")
