#!/usr/bin/env python3
"""Write web/data2.js: universal machine version 2's network for the browser.

From experiments/fast-universal-machine: the step table with the tour machines (steps3.json, from collect_tail.py) and
the width-8 network trained on it (fixtures2/net3_d8_seed0.json, 23,844 parameters). The format is data.js's, with
version 2, outputs read as the tokens they emit, and the training windows as token ids (trainIds), three per window."""
import json
from pathlib import Path

WEB = Path(__file__).resolve().parent
X = WEB.parent / "experiments" / "fast-universal-machine"
S = json.loads((X / "steps3.json").read_text())
F = json.loads((X / "fixtures2" / "net3_d8_seed0.json").read_text())
assert F["vin"] == S["vin"] and F["vout"] == S["vout"]
vin, vout = S["vin"], S["vout"]
iin = {t: i for i, t in enumerate(vin)}
emits = {o: ([] if o == "<halt>" else o.split(" ")) for o in vout}
missing = {t for e in emits.values() for t in e if t not in iin}
assert not missing, f"emitted tokens not in the input vocabulary: {sorted(missing)[:5]}"
train = [iin[t] for s, f in zip(S["steps"], S["first"]) if f >= 0 for t in s.split("\u0001")]
params = sum(len(m) * len(m[0]) for m in F["weights"].values())
data = {"version": 2, "vin": vin, "vout": vout, "emits": emits, "heads": F["heads"],
        "weights": {k: [[round(x, 6) for x in row] for row in v] for k, v in F["weights"].items()},
        "trainIds": train, "params": params,
        "training": {"random_machines": S["machines"], "tours": S["tours"], "windows": len(train) // 3}}
(WEB / "data2.js").write_text("// Generated by web/build_data2.py from experiments/fast-universal-machine. Do not edit.\n"
                              "window.TCT_DATA2 = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"{len(vin)} input tokens, {len(vout)} outputs, {params:,} parameters, {len(train) // 3:,} training windows; "
      f"wrote web/data2.js ({(WEB / 'data2.js').stat().st_size // 1024} KB)")
