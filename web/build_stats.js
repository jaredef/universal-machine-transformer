// What each program costs the network, for tlf.html: every program in runviz.js, with its default input, run by the
// version-2 network through the delta decoder (core.js DeltaRun), plus the sieve to 1,680 (the largest run on the page;
// a few minutes). Each run is checked against a direct run of the rules, configuration by configuration. Generates
// web/program-stats.js:  node build_stats.js
global.window = global;
require("./data2.js");
const T = require("./core.js"), PR = require("./programs.js"), CU = require("./curves.js"), P = require("./primes.js"), fs = require("fs");
global.TCT_PROGRAMS = PR; global.TCT_CURVES = CU; global.TCT_PRIMES = P;
const RV = require("./runviz.js"), e = new T.Engine(window.TCT_DATA2);
const src = { counter: PR.programs[1], sort: PR.programs[2], count: PR.programs[4], add: PR.programs[3], collatz: PR.programs[0], fib: PR.programs[5],
  dragon: CU.curves[0], koch: CU.curves[1], fibword: CU.curves[2], bb4: null, sieve: null };
function measure(id, param) {
  const m = RV.setup(id, { src: src[id] || {} }, param), want = RV.direct(m.start, m.rules, m.tape), machine = T.parseMachine(m.start, m.rules);
  let i = 0, matched = 1;
  const r = new T.DeltaRun(e, machine, m.tape, (run) => {
    const w = want[++i], g = { state: run.verdict ? "qa" : run.simState(), head: run.simHead(), tape: run.simTape().join("").replace(/_+$/, "") };
    if (w && g.state === w.state && g.tape === w.tape && (w.final || g.head === w.head)) matched++;
  });
  const t0 = Date.now(); while (!r.verdict) r.run(1e7);
  const out = { id, param, states: machine.order.length, rules: m.rules.length, ring: r.encoded.length + 1, steps: want.length - 1,
    utmSteps: r.utmSteps, passes: r.passes, read: r.read, distinct: r.distinct, unseen: r.unseen, wrong: r.disagree, matched, configs: want.length };
  console.log(JSON.stringify(out), Date.now() - t0 + " ms");
  if (matched !== want.length || r.disagree) throw new Error(id + " did not match its direct run");
  return out;
}
const rows = Object.keys(RV.SPECS).map((id) => measure(id, RV.SPECS[id].param.value));
const big = measure("sieve", "1680");
const sum = (k) => rows.reduce((s, x) => s + x[k], 0);
const all = { programs: rows.length, passes: sum("passes"), steps: sum("steps"), utmSteps: sum("utmSteps"), read: sum("read"), unseen: sum("unseen"), wrong: sum("wrong") };
fs.writeFileSync(__dirname + "/program-stats.js", "// Generated by build_stats.js: what each program costs the network (default inputs), and the sieve to 1,680.\n" +
  "window.TCT_STATS = " + JSON.stringify({ rows, big, all }) + ";\n");
console.log("all", JSON.stringify(all));
