// Finds the windows the network never saw in training that come up while it runs the sieve of Eratosthenes to 120,
// with the transcript around each, for inside.html. Generates web/inside-data.js:  node build_inside.js
// The loop is the lagging-window decoder (core.js FastRun), keeping track of where each window is read.
global.window = global;
require("./data2.js");
const TCT = require("./core.js"), P = require("./primes.js"), fs = require("fs");
const e = new TCT.Engine(window.TCT_DATA2), N = 120, s = P.sieve(N), m = TCT.parseMachine(s.start, s.rules);
const cells = e.utm.encode(m, s.tape).split(""); cells[0] = "find:" + cells[0];
const ring = ["#"].concat(cells);
let cap = 1 << 22, T = new Int32Array(cap), n = 0, k = 0, passes = 0, ringStart = -1, readStart = 1, utmSteps = 0;
T[n++] = e.id[ring[ring.length - 1]]; ring.forEach(t => { T[n++] = e.id[t]; });
const K = e.K, BID = e.id["#"], seen = new Set(), found = [];
for (;;) {
  const a = T[k], b = T[k + 1], c = T[k + 2], key = (a * K + b) * K + c;
  let v = e.memo.get(key);
  if (v === undefined) { v = e.net.forward([a, b, c]).best; e.memo.set(key, v); }
  if (!seen.has(key)) {
    seen.add(key);
    if (!e.trained.has(key)) {
      let end = k + 2; while (end < n && T[end] !== BID) end++;     // the ring being read is T[readStart, end)
      const tok = (i, j) => Array.from(T.subarray(i, j), x => e.vin[x]);
      found.push({ pass: passes, utmStep: utmSteps, window: [a, b, c].map(x => e.vin[x]), at: k + 1 - readStart, ring: end - readStart,
                   before: tok(Math.max(k - 14, readStart), k), after: tok(k + 3, Math.min(k + 17, end)),
                   exact: e.exact([a, b, c]), wrote: e.emitIds[v].map(x => e.vin[x]).join(" ") });
    }
  }
  const out = e.emitIds[v];
  if (!out.length) break;
  if (b === BID) { if (ringStart >= 0) utmSteps++; ringStart = n; readStart = k + 1; }
  if (n + 2 >= cap) { T.copyWithin(0, k, n); n -= k; ringStart -= k; readStart -= k; k = 0; }
  for (const t of out) T[n++] = t;
  k++; passes++;
}
console.log(passes, "passes (and the halt),", found.length, "windows never in training");
found.forEach(f => console.log(f.pass, f.window.join(" "), "->", f.wrote, f.wrote === f.exact ? "right" : "WRONG"));
fs.writeFileSync(__dirname + "/inside-data.js", "// Generated by web/build_inside.js. Do not edit.\n" +
  "window.TCT_INSIDE = " + JSON.stringify({ program: "the sieve of Eratosthenes to " + N, passes: passes, unseen: found }) + ";\n");
