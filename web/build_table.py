#!/usr/bin/env python3
"""Write web/table.js for the training page: the universal machine's whole step table (14,849 steps), from
experiments/smallest-training-set/steps.json.

Each step is three input tokens and the exact output; `first` is the index of the first of lag3's random machines that
produces it, so the training set of the first N machines is every step with 0 <= first < N, exactly as in the
experiment. The vocabularies are trimmed to the tokens the table uses (429 in, 434 out); `vinFull` and `voutFull` map
them back to data.js's full vocabularies, so a network trained in the browser can run on the other pages."""
import json
from pathlib import Path

WEB = Path(__file__).resolve().parent
S = json.loads((WEB.parent / "experiments" / "smallest-training-set" / "steps.json").read_text())
steps = [s.split("\u0001") for s in S["steps"]]
used_in = {t for w in steps for t in w}
used_out = set(S["labels"])
vin = [t for t in S["vin"] if t in used_in]                # data.js order, trimmed
vout = [t for t in S["vout"] if t in used_out]
iin, iout = {t: i for i, t in enumerate(vin)}, {t: i for i, t in enumerate(vout)}
table = {
    "vin": vin, "vout": vout,
    "vinFull": [S["vin"].index(t) for t in vin], "voutFull": [S["vout"].index(t) for t in vout],
    "steps": [iin[t] for w in steps for t in w], "labels": [iout[y] for y in S["labels"]],
    "first": S["first"], "machines": S["n_max"], "growth": S["growth"], "tests": S["tests"],
}
(WEB / "table.js").write_text("// Generated by web/build_table.py from experiments/smallest-training-set. Do not edit.\n"
                              "window.TCT_TABLE = " + json.dumps(table, separators=(",", ":")) + ";\n")
print(f"{len(steps)} steps, {len(vin)} input tokens, {len(vout)} outputs; "
      f"wrote web/table.js ({(WEB / 'table.js').stat().st_size // 1024} KB)")
